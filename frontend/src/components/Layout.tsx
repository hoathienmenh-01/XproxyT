function MenuIcon() {
  return (
    <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
      <line x1="4" y1="6" x2="20" y2="6" />
      <line x1="4" y1="12" x2="20" y2="12" />
      <line x1="4" y1="18" x2="20" y2="18" />
    </svg>
  );
}

function CloseIcon() {
  return (
    <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
      <line x1="18" y1="6" x2="6" y2="18" />
      <line x1="6" y1="6" x2="18" y2="18" />
    </svg>
  );
}

export default function Layout() {
  const {t} = useI18n();
  const [health, setHealth] = useState<'online' | 'offline' | 'checking'>('checking');
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false);

  useEffect(() => {
    const check = () => {
      fetch('/health').then(r => setHealth(r.ok ? 'online' : 'offline')).catch(() => setHealth('offline'));
    };
    check();
    const timer = window.setInterval(check, 10000);
    return () => window.clearInterval(timer);
  }, []);

  const closeMobileMenu = useCallback(() => {
    setMobileMenuOpen(false);
  }, []);

  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape' && mobileMenuOpen) {
        setMobileMenuOpen(false);
      }
    };
    document.addEventListener('keydown', handleKeyDown);
    return () => document.removeEventListener('keydown', handleKeyDown);
  }, [mobileMenuOpen]);

  useEffect(() => {
    if (mobileMenuOpen) {
      document.body.style.overflow = 'hidden';
    } else {
      document.body.style.overflow = '';
    }
    return () => { document.body.style.overflow = ''; };
  }, [mobileMenuOpen]);

  return (
    <div className="app-root">
      {/* Mobile hamburger button */}
      <button
        className="mobile-nav-toggle"
        onClick={() => setMobileMenuOpen(!mobileMenuOpen)}
        aria-label={mobileMenuOpen ? 'Close menu' : 'Open menu'}
        aria-expanded={mobileMenuOpen}
      >
        {mobileMenuOpen ? <CloseIcon /> : <MenuIcon />}
      </button>

      <header className={`header${mobileMenuOpen ? ' mobile-open' : ''}`} role="navigation" aria-label="Primary">
        <div className="brand">
          <span className="brand-icon">◆</span>
          <span className="brand-text">XproxyT</span>
        </div>

        <div className="sidebar-status">
          <span className={`sidebar-status-dot status-${health}`} />
          <span className="sidebar-status-label">
            {health === 'online' ? 'Connected' : health === 'offline' ? 'Disconnected' : 'Checking…'}
          </span>
        </div>

        <nav className="nav">
          <div className="nav-section-title">Menu</div>
          <ul className="nav-list">
            {navItems.map((item) => (
              <li key={item.to}>
                <NavLink
                  to={item.to}
                  className={({isActive}) => isActive ? 'active nav-link' : 'nav-link'}
                  onClick={closeMobileMenu}
                >
                  {icons[item.icon] || icons.dashboard}
                  <span>{t(item.labelKey)}</span>
                </NavLink>
              </li>
            ))}
          </ul>
        </nav>

        <div className="sidebar-footer">
          <div className="sidebar-version">v0.1.0</div>
        </div>
      </header>

      {/* Mobile backdrop */}
      {mobileMenuOpen && (
        <div className="mobile-backdrop" onClick={closeMobileMenu} aria-hidden="true" />
      )}

      <div className="main">
        <main className="content" tabIndex={-1}>
          <Outlet />
        </main>
      </div>
    </div>
  );
}